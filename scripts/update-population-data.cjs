// Refresh the embedded 2020 estimates from Pew's public interactive dataset.
// Run with Node 22.19+ / 24+: node --use-system-ca scripts/update-population-data.cjs
// No downloaded JavaScript is executed. Only its JSON data is parsed.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const sourceUrl = 'https://www.pewresearch.org/religion/feature/religious-composition-by-country-2010-2020/';
const geographyBase = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/';
const normalize = value => value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]/g, '');

async function download(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} fetching ${url}`);
  return response.text();
}

async function main() {
  const html = await download(sourceUrl);
  const scriptUrl = [...html.matchAll(/<script[^>]+src=["']([^"']+)/g)]
    .map(match => match[1]).find(url => url.includes('/grf-table/build/index.js'));
  if (!scriptUrl || new URL(scriptUrl).origin !== new URL(sourceUrl).origin) throw new Error('Pew table script not found');
  const [script, countriesJson, unitsJson] = await Promise.all([
    download(scriptUrl),
    download(geographyBase + 'ne_10m_admin_0_countries.geojson'),
    download(geographyBase + 'ne_10m_admin_0_map_units.geojson')
  ]);
  const match = script.match(/JSON\.parse\('(\[\{"Region":[\s\S]*?)'\)/);
  if (!match) throw new Error('Pew JSON format changed; review the source before updating');
  const rows = JSON.parse(match[1]);
  const countries = JSON.parse(countriesJson).features.map(f => f.properties);
  const units = JSON.parse(unitsJson).features.map(f => f.properties);
  const aliases = {
    'Cape Verde': 'Cabo Verde', 'Czech Republic': 'Czechia',
    'Palestinian territories': 'Palestine', 'St. Lucia': 'Saint Lucia',
    'St. Vincent and the Grenadines': 'Saint Vincent and the Grenadines',
    'U.S. Virgin Islands': 'United States Virgin Islands', 'United States': 'United States of America'
  };
  function locate(name) {
    if (name === 'Channel Islands') {
      const jersey = locate('Jersey'), guernsey = locate('Guernsey');
      return { lat: (jersey.lat + guernsey.lat) / 2, lon: (jersey.lon + guernsey.lon) / 2 };
    }
    const wanted = normalize(aliases[name] || name);
    const point = countries.find(p => [p.NAME, p.ADMIN].some(n => normalize(n) === wanted))
      || units.find(p => [p.NAME, p.GEOUNIT].some(n => n && normalize(n) === wanted));
    if (!point || !Number.isFinite(point.LABEL_Y) || !Number.isFinite(point.LABEL_X)) throw new Error(`No map point for ${name}`);
    return { lat: point.LABEL_Y, lon: point.LABEL_X };
  }
  function statistics(row) {
    const percent = row.Christians / row.Total * 100;
    return {
      count: row.Christians < 10000 ? 10000 : Math.round(row.Christians / 10000) * 10000,
      countBelow: row.Christians < 10000,
      percent: percent < 0.1 ? 0.1 : percent > 99.9 ? 99.9 : Math.round(percent * 10) / 10,
      percentBound: percent < 0.1 ? '<' : percent > 99.9 ? '>' : ''
    };
  }
  const current = rows.filter(row => row.Year === 2020 && row.Country !== 'All Countries');
  if (current.length !== 201 || new Set(current.map(r => r.Country)).size !== 201) throw new Error('Unexpected coverage; review dataset');
  const world = rows.find(row => row.Year === 2020 && row.Region === 'World');
  if (!world) throw new Error('Global estimate missing');
  const dataset = {
    year: 2020,
    published: '2025-06-09',
    retrieved: new Date().toISOString().slice(0, 10),
    source: 'Pew Research Center', sourceUrl,
    methodologyUrl: 'https://www.pewresearch.org/religion/2025/06/09/global-religious-change-methodology/',
    sourceScript: scriptUrl,
    sourceSha256: crypto.createHash('sha256').update(script).digest('hex'),
    geographySource: 'https://www.naturalearthdata.com/',
    world: statistics(world),
    countries: current.map(row => {
      const point = locate(row.Country);
      return { name: row.Country, region: row.Region, ...statistics(row),
        lat: Math.round(point.lat * 1000) / 1000, lon: Math.round(point.lon * 1000) / 1000 };
    })
  };
  const output = '/* Christian affiliation estimates, 2020; published by Pew Research Center in 2025.\n'
    + '   Counts rounded to 10,000; countBelow means an upper bound, never an exact count.\n'
    + '   Percentages rounded to 0.1%; bounds preserved. Not estimates for 2026.\n'
    + '   Map label points: Natural Earth (public domain); Channel Islands uses the\n'
    + '   midpoint of the Jersey and Guernsey label points.\n'
    + '   Generated by scripts/update-population-data.cjs. See README for attribution. */\n'
    + 'var CHRISTIAN_POPULATION = ' + JSON.stringify(dataset, null, 2) + ';\n';
  fs.writeFileSync(path.join(__dirname, '../population-data.js'), output);
  console.log(`Wrote ${dataset.countries.length} country/territory estimates for ${dataset.year}.`);
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
